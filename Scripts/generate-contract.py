#!/usr/bin/env python3
"""Generate the contract's Kotlin client from an allowlist of operations (ADR-0061).

Reads `contract/openapi.json` (the platform's contract, vendored byte-identical) and `contract/operations.txt` (the
operations this app may call). Emits, under `core/networking/contract/`:

- `ContractModels.kt`: an `internal` `@Serializable` class for every schema the allowed operations reach, and nothing
  else. Its `toString` prints its name only, never a value. A contract enum becomes a value class over its wire string, with the known values as constants, so a value the
  app does not know decodes and stays opaque instead of failing.
- `ContractOperations.kt`: each allowed operation as a typed `ContractOperation<Request, Response>`, with its verb,
  path template, path and query parameters, and the serializers of its body and its answer. No path or type is typed
  by hand anywhere else.

It refuses, by name, what it does not understand (`oneOf`, `allOf`, `anyOf`, a discriminator, an operation outside
the four prefixes) instead of generating something wrong. Deterministic: the same inputs give the same bytes, so
`Scripts/check-contract.sh` can regenerate and compare.

Usage: generate-contract.py [--out DIR]   (default: the source tree)
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "contract" / "openapi.json"
ALLOWLIST = ROOT / "contract" / "operations.txt"
# The dev-only token route the platform leaves out of its contract on purpose (ADR-0061 point 5, ADR-0062). Merged in,
# never into the vendored file, so the pin keeps proving the platform's bytes.
DEV_AUTH = ROOT / "contract" / "dev-auth.json"
DEV_PATHS = ("/dev/token",)
PACKAGE = "com.luismejias.lumemedlink.core.networking.contract"
DEFAULT_OUT = ROOT / "composeApp/src/commonMain/kotlin" / pathlib.Path(*PACKAGE.split("."))
# `/v1/me/` is the caller's own account: its role, MFA, devices and phone. Checked on 0.128.0: nothing clinical under it.
ALLOWED_PREFIXES = ("/v1/patient/", "/v1/directory/", "/v1/reference/", "/v1/me/")
# Two platform routes every app tier has, by their exact path: the kill switch (§8.15) and the security-event channel
# (ADR-0023). Exact, so that `/v1/platform/security-events`, the platform's own trail, stays out.
ALLOWED_EXACT = ("/v1/me", "/v1/patient", "/v1/app-availability", "/v1/security-events")
UNSUPPORTED = ("oneOf", "allOf", "anyOf", "discriminator", "not")
KOTLIN_KEYWORDS = {
    "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null",
    "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var",
    "when", "while",
}
HEADER = (
    "// GENERATED by Scripts/generate-contract.py from contract/openapi.json ({version}). Do not edit: change\n"
    "// contract/operations.txt or the generator, and run it again (ADR-0061).\n"
)


class Refused(Exception):
    """Something the generator will not guess at."""


def fail(message: str) -> None:
    raise Refused(message)


def allowed_path(path: str) -> bool:
    return path in ALLOWED_EXACT or path in DEV_PATHS or path.startswith(ALLOWED_PREFIXES)


def read_allowlist() -> list[str]:
    ids = []
    for raw in ALLOWLIST.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            ids.append(line.split()[0])
    if len(ids) != len(set(ids)):
        fail("operations.txt names an operation twice")
    return ids


def pascal(name: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", name)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def camel(name: str) -> str:
    p = pascal(name)
    return p[:1].lower() + p[1:]


def constant(name: str) -> str:
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    s = re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_").upper()
    return s if not s[:1].isdigit() else "V_" + s


def identifier(name: str) -> str:
    ident = camel(name)
    return f"`{ident}`" if ident in KOTLIN_KEYWORDS else ident


def kdoc(text: str | None, indent: str) -> str:
    if not text:
        return ""
    body = " ".join(text.split()).replace("*/", "*&#47;")
    words, lines, line = body.split(" "), [], ""
    width = 116 - len(indent) - 3
    for w in words:
        if line and len(line) + 1 + len(w) > width:
            lines.append(line)
            line = w
        else:
            line = f"{line} {w}" if line else w
    lines.append(line)
    if len(lines) == 1 and len(lines[0]) <= width - 4:
        return f"{indent}/** {lines[0]} */\n"
    return f"{indent}/**\n" + "".join(f"{indent} * {l}\n" for l in lines) + f"{indent} */\n"


class Generator:
    def __init__(self, spec: dict):
        self.spec = spec
        self.schemas = spec.get("components", {}).get("schemas", {})
        self.classes: dict[str, str] = {}  # Kotlin name -> source
        self.enums: dict[str, str] = {}
        self.visiting: set[str] = set()

    # ── Types ────────────────────────────────────────────────────────────────────────────────────────
    def check(self, schema: dict, where: str) -> None:
        for key in UNSUPPORTED:
            if key in schema:
                fail(f"{where}: `{key}` is not supported by the generator")
        if "additionalProperties" in schema and schema.get("additionalProperties") not in (False, None):
            fail(f"{where}: `additionalProperties` is not supported by the generator")

    def type_of(self, schema: dict, owner: str, prop: str) -> str:
        """The Kotlin type of [schema], declaring any class or enum it needs. Nullability is the caller's."""
        where = f"{owner}.{prop}"
        self.check(schema, where)
        ref = schema.get("$ref")
        if ref:
            return self.named(ref.rsplit("/", 1)[-1])
        kind = schema.get("type")
        if "enum" in schema:
            if kind not in (None, "string"):
                fail(f"{where}: a non-string enum is not supported")
            return self.enum(owner + pascal(prop), schema)
        if kind == "string":
            return "String"
        if kind == "integer":
            return "Long" if schema.get("format") == "int64" else "Int"
        if kind == "number":
            return "Double"
        if kind == "boolean":
            return "Boolean"
        if kind == "array":
            items = schema.get("items")
            if not isinstance(items, dict):
                fail(f"{where}: an array without items")
            return f"List<{self.type_of(items, owner, prop + 'Item')}>"
        if kind == "object" or "properties" in schema:
            return self.object(owner + pascal(prop), schema)
        fail(f"{where}: a schema without a type")
        return ""

    def named(self, name: str) -> str:
        if name not in self.schemas:
            fail(f"$ref to a missing schema: {name}")
        kotlin = pascal(name)
        if kotlin not in self.classes and kotlin not in self.enums and kotlin not in self.visiting:
            schema = self.schemas[name]
            self.check(schema, name)
            if "enum" in schema:
                self.enum(kotlin, schema)
            elif schema.get("type") == "object" or "properties" in schema:
                self.object(kotlin, schema, description=schema.get("description"))
            else:
                fail(f"{name}: a top-level schema that is neither an object nor an enum")
        return kotlin

    def enum(self, name: str, schema: dict) -> str:
        if name in self.enums:
            return name
        values = schema["enum"]
        if any(not isinstance(v, str) for v in values):
            fail(f"{name}: an enum with a non-string value")
        lines = [kdoc(schema.get("description") or "A value of the contract's vocabulary; an unknown one stays as sent.", "")]
        lines.append("@Serializable\n@JvmInline\n")
        lines.append(f"internal value class {name}(val wire: String) {{\n")
        lines.append("    companion object {\n")
        for v in values:
            lines.append(f"        val {constant(v)}: {name} = {name}(\"{v}\")\n")
        lines.append("    }\n}\n")
        self.enums[name] = "".join(lines)
        return name

    def object(self, name: str, schema: dict, description: str | None = None) -> str:
        if name in self.classes:
            return name
        self.visiting.add(name)
        props = schema.get("properties", {})
        required = set(schema.get("required", []))
        fields = []
        for wire in props:
            prop = props[wire]
            if not isinstance(prop, dict):
                fail(f"{name}.{wire}: not a schema")
            kotlin_type = self.type_of(prop, name, wire)
            nullable = prop.get("nullable") is True or wire not in required
            ident = identifier(wire)
            serial = "" if camel(wire) == wire else f'    @SerialName("{wire}")\n'
            doc = kdoc(prop.get("description"), "    ")
            default = " = null" if wire not in required else ""
            fields.append(f"{doc}{serial}    val {ident}: {kotlin_type}{'?' if nullable else ''}{default},\n")
        self.visiting.discard(name)
        head = kdoc(description, "")
        if not fields:
            body = f"{head}@Serializable\ninternal class {name}\n"
        else:
            # Kotlin's own toString would print a patient's name, phone or address into any log or crash that touches
            # the value (§8.1): every class prints its name only, as the app's domain types already do.
            body = (
                f"{head}@Serializable\ninternal data class {name}(\n" + "".join(fields)
                + f") {{\n    override fun toString(): String = \"{name}\"\n}}\n"
            )
        self.classes[name] = body
        return name

    # ── Operations ───────────────────────────────────────────────────────────────────────────────────
    def operations(self, allowed: list[str]) -> list[dict]:
        found = {}
        for path, item in self.spec["paths"].items():
            for verb, op in item.items():
                if isinstance(op, dict) and "operationId" in op:
                    found[op["operationId"]] = (verb.upper(), path, op, item.get("parameters", []))
        result = []
        for op_id in allowed:
            if op_id not in found:
                fail(f"operations.txt names {op_id}, which the contract does not have")
            verb, path, op, shared = found[op_id]
            if not allowed_path(path):
                fail(f"{op_id} is {verb} {path}: outside /v1/patient, /v1/directory, /v1/reference, /v1/me and the two platform routes")
            params = shared + op.get("parameters", [])
            path_params = [p["name"] for p in params if p.get("in") == "path"]
            query = [(p["name"], bool(p.get("required"))) for p in params if p.get("in") == "query"]
            if sorted(path_params) != sorted(re.findall(r"\{([^}]+)\}", path)):
                fail(f"{op_id}: the path's parameters and the declared ones differ")
            body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            request = self.type_of(body, pascal(op_id), "Request") if body else "Unit"
            response = "Unit"
            for code in sorted(op.get("responses", {})):
                if code.startswith("2"):
                    content = op["responses"][code].get("content", {}).get("application/json", {}).get("schema")
                    response = self.type_of(content, pascal(op_id), "Response") if content else "Unit"
                    break
            result.append({
                "id": op_id, "verb": verb, "path": path, "path_params": path_params, "query": query,
                "request": request, "response": response, "summary": op.get("summary") or op.get("description"),
            })
        return result


def serializer(kotlin_type: str) -> str:
    if kotlin_type.startswith("List<"):
        return f"ListSerializer({serializer(kotlin_type[5:-1])})"
    if kotlin_type in ("Unit", "String", "Int", "Long", "Double", "Boolean"):
        return f"{kotlin_type}.serializer()"
    return f"{kotlin_type}.serializer()"


def render(gen: Generator, ops: list[dict], version: str) -> dict[str, str]:
    header = HEADER.format(version=version)
    declarations = "\n".join(gen.enums[k] for k in sorted(gen.enums))
    declarations += ("\n" if gen.enums else "") + "\n".join(gen.classes[k] for k in sorted(gen.classes))
    imports = ["import kotlinx.serialization.Serializable"]
    if "@SerialName(" in declarations:
        imports.insert(0, "import kotlinx.serialization.SerialName")
    if "@JvmInline" in declarations:
        imports.append("import kotlin.jvm.JvmInline")
    models = (
        header + f"@file:Suppress(\"ktlint\", \"MaxLineLength\", \"LongParameterList\")\n\npackage {PACKAGE}\n\n"
        + "\n".join(imports) + "\n\n" + declarations
    )
    lines = [
        header, "@file:Suppress(\"ktlint\", \"MaxLineLength\")\n\n", f"package {PACKAGE}\n\n",
        "import kotlinx.serialization.builtins.ListSerializer\nimport kotlinx.serialization.builtins.serializer\n\n",
        "/** The operations this app may call (contract/operations.txt), typed by their body and their answer. */\n",
        "internal object ContractOperations {\n",
    ]
    for op in ops:
        lines.append(kdoc(op["summary"], "    "))
        query = ", ".join(f'ContractQuery("{n}", required = {str(r).lower()})' for n, r in op["query"])
        path_params = ", ".join(f'"{p}"' for p in op["path_params"])
        lines.append(
            f"    val {constant(op['id'])}: ContractOperation<{op['request']}, {op['response']}> = ContractOperation(\n"
            f"        id = \"{op['id']}\",\n"
            f"        verb = ContractVerb.{op['verb']},\n"
            f"        path = \"{op['path']}\",\n"
            f"        pathParameters = listOf({path_params}),\n"
            f"        query = listOf({query}),\n"
            f"        request = {serializer(op['request'])},\n"
            f"        response = {serializer(op['response'])},\n"
            f"    )\n\n"
        )
    lines[-1] = lines[-1].rstrip("\n") + "\n"
    lines.append("}\n")
    return {"ContractModels.kt": models, "ContractOperations.kt": "".join(lines)}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    spec = json.loads(CONTRACT.read_text())
    dev = json.loads(DEV_AUTH.read_text())
    for path in dev["paths"]:
        if path not in DEV_PATHS or path in spec["paths"]:
            print(f"generate-contract: REFUSED — dev-auth.json may add only {DEV_PATHS}, and none the contract has", file=sys.stderr)
            return 1
    spec["paths"] = {**spec["paths"], **dev["paths"]}
    clash = set(dev["components"]["schemas"]) & set(spec["components"]["schemas"])
    if clash:
        print(f"generate-contract: REFUSED — dev-auth.json redefines {sorted(clash)}", file=sys.stderr)
        return 1
    spec["components"]["schemas"] = {**spec["components"]["schemas"], **dev["components"]["schemas"]}
    if not str(spec.get("openapi", "")).startswith("3.0"):
        print(f"generate-contract: REFUSED — OpenAPI {spec.get('openapi')} is not 3.0", file=sys.stderr)
        return 1
    gen = Generator(spec)
    try:
        ops = gen.operations(read_allowlist())
    except Refused as refused:
        print(f"generate-contract: REFUSED — {refused}", file=sys.stderr)
        return 1
    args.out.mkdir(parents=True, exist_ok=True)
    for name, text in render(gen, ops, spec["info"]["version"]).items():
        (args.out / name).write_text(text)
    print(f"generate-contract: {len(ops)} operations, {len(gen.classes)} classes, {len(gen.enums)} enums → {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
